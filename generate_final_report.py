import re

def body(doc, text, size=Pt(10.5)):
    """Add body paragraph 五号宋体 with first-line indent.
    Auto-detects [N] reference markers and renders them as superscript."""
    p = new_para(doc, cn=BODY_CN, size=size, indent=True)
    # Split text by [N] patterns and render references as superscript
    parts = re.split(r'(\[\d+(?:[,-]\d+)*\])', text)
    for part in parts:
        if re.match(r'\[\d+(?:[,-]\d+)*\]', part):
            run_add(p, part, cn=BODY_CN, size=size, superscript=True)
        else:
            run_add(p, part, cn=BODY_CN, size=size)
    return p

def body_with_refs(doc, segments, size=Pt(10.5)):
    """Body paragraph with mixed text and superscript references.
    segments is list of (text, is_superscript) tuples."""
    p = new_para(doc, cn=BODY_CN, size=size, indent=True)
    for seg in segments:
        if isinstance(seg, str):
            run_add(p, seg, cn=BODY_CN, size=size)
        elif isinstance(seg, tuple):
            text, sup = seg
            run_add(p, text, cn=BODY_CN, size=size, superscript=sup)
    return p

